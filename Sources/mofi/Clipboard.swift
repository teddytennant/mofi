import AppKit
import CryptoKit

struct ClipItem: Codable {
    var kind: String // "text" | "image"
    var text: String
    var image: String?
    var width: Int?
    var height: Int?
    var time: Double
}

/// Clipboard history. macOS has no change notification, so we poll
/// NSPasteboard.changeCount (an integer read; effectively free).
final class ClipboardStore {
    private(set) var items: [ClipItem] = []
    var maxItems = 500
    var images = true
    var ignore: Set<String> = []
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var saveScheduled = false
    private let file = Paths.dataDir + "/clipboard.json"
    let imageDir = Paths.dataDir + "/clipboard-images"

    init() {
        if let data = FileManager.default.contents(atPath: file),
           let list = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = list
        }
    }

    func configure(_ c: Config) {
        maxItems = max(1, c.clipMax)
        images = c.clipImages
        ignore = c.clipIgnore
        timer?.invalidate()
        timer = nil
        guard c.clipEnabled else { return }
        let t = Timer(timeInterval: Double(c.clipPollMs) / 1000, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.05
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        let c = pb.changeCount
        guard c != lastChange else { return }
        lastChange = c
        capture(pb)
    }

    private func capture(_ pb: NSPasteboard) {
        let types = Set((pb.types ?? []).map(\.rawValue))
        // nspasteboard.org markers that password managers set.
        for t in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
            where types.contains(t) { return }
        if let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, ignore.contains(app) { return }
        if let s = pb.string(forType: .string) {
            if !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { addText(s) }
            return
        }
        if images, let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) { addImage(data) }
    }

    func addText(_ s: String) {
        items.removeAll { $0.kind == "text" && $0.text == s }
        items.insert(ClipItem(kind: "text", text: s, time: Date().timeIntervalSince1970), at: 0)
        trim()
        save()
    }

    private func addImage(_ data: Data) {
        guard let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) else { return }
        let hash = SHA256.hash(data: png).prefix(10).map { String(format: "%02x", $0) }.joined()
        let name = hash + ".png"
        Paths.ensure(imageDir)
        let path = imageDir + "/" + name
        if !FileManager.default.fileExists(atPath: path) {
            FileManager.default.createFile(atPath: path, contents: png, attributes: [.posixPermissions: 0o600])
        }
        items.removeAll { $0.image == name }
        items.insert(ClipItem(kind: "image", text: "image \(rep.pixelsWide)×\(rep.pixelsHigh)", image: name,
                              width: rep.pixelsWide, height: rep.pixelsHigh, time: Date().timeIntervalSince1970), at: 0)
        trim()
        save()
    }

    func imagePath(_ item: ClipItem) -> String? { item.image.map { imageDir + "/" + $0 } }

    /// Put an entry back on the pasteboard and move it to the top.
    func copy(_ index: Int) {
        guard items.indices.contains(index) else { return }
        let item = items.remove(at: index)
        items.insert(item, at: 0)
        let pb = NSPasteboard.general
        pb.clearContents()
        if item.kind == "image", let p = imagePath(item), let img = NSImage(contentsOfFile: p) {
            pb.writeObjects([img])
        } else {
            pb.setString(item.text, forType: .string)
        }
        lastChange = pb.changeCount
        items[0].time = Date().timeIntervalSince1970
        save()
    }

    func setText(_ s: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(s, forType: .string)
    }

    func delete(_ index: Int) {
        guard items.indices.contains(index) else { return }
        let item = items.remove(at: index)
        removeImageIfUnused(item)
        save()
    }

    func clear() {
        items.removeAll()
        try? FileManager.default.removeItem(atPath: imageDir)
        save()
    }

    private func trim() {
        while items.count > maxItems { removeImageIfUnused(items.removeLast()) }
    }

    private func removeImageIfUnused(_ item: ClipItem) {
        guard let name = item.image, !items.contains(where: { $0.image == name }) else { return }
        try? FileManager.default.removeItem(atPath: imageDir + "/" + name)
    }

    private func save() {
        guard !saveScheduled else { return }
        saveScheduled = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            self.saveScheduled = false
            Paths.ensure(Paths.dataDir)
            if let data = try? JSONEncoder().encode(self.items) {
                FileManager.default.createFile(atPath: self.file, contents: data, attributes: [.posixPermissions: 0o600])
            }
        }
    }

    /// Synthesize Cmd-V into the frontmost app. Needs Accessibility.
    static func pasteIntoFrontApp() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        guard AXIsProcessTrustedWithOptions(opts) else {
            log("paste_on_select needs Accessibility permission for \(Bundle.main.executablePath ?? "mofi")")
            return
        }
        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
